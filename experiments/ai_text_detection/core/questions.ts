// ---------------------------------------------------------------------------
// Answer shapes returned by the API.
// ---------------------------------------------------------------------------

export interface NoulAnswer {
  type: 'noul';
  noul: number;
}
export interface ScoreAnswer {
  type: 'score';
  score: number;
  confidence: number;
  probabilities?: Record<string, number>;
  legend?: Record<string, string>;
}

/** The validated answer set for one chunk. */
export interface Answers {
  ai_written: NoulAnswer;
  tells: ScoreAnswer;
  staging: NoulAnswer;
  rhythm: NoulAnswer;
  inflation: NoulAnswer;
  formatting: NoulAnswer;
  chat_residue: NoulAnswer;
  specifics: NoulAnswer;
}

