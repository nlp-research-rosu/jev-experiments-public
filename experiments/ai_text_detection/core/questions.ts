/**
 * The questions we ask Jev (TypeSafe's System One decision model) about a chunk of text.
 *
 * Jev does not generate prose. It returns typed answers: Noul (probability of yes),
 * Score (position on ordered levels) and Choice. Docs: https://docs.typesafe.ai
 *
 * Two rules from the Jev docs shape everything here:
 *  1. Every Score level is evaluated on its own. The model never sees a level's number or its
 *     neighbours, so each level must describe a concrete situation, never a degree.
 *  2. Phrase Nouls so that a high value means "yes".
 *
 * The tell families follow github.com/blader/humanizer (MIT), which distils Wikipedia's
 * "Signs of AI writing". Its core insight: a model picks the choice that fits the widest range of
 * readers and subjects, while a person writes for one reader and one subject, so human choices are
 * uneven and specific. Structural habits persist across model releases; vocabulary drifts. The
 * structural families therefore carry more weight than word lists.
 */

export interface NoulQuestion {
  type: 'noul';
  instructions: string;
  criteria?: { true: string; false: string };
}
export interface ScoreQuestion {
  type: 'score';
  instructions: string;
  criteria: string[];
}
export type JevQuestion = NoulQuestion | ScoreQuestion;

